"""Write rooms/maxarm_petri/{room.json, petri_base.xml, petri_lid.xml} from
hardware/maxarm/petri.py (dish dimensions and the layout). Run it after
changing either; `hardware.maxarm.test_sim_maxarm` fails when the files are
stale. The arm's base pose and the dishes' world poses are derived here, so
the room never carries a hand-typed copy of a number petri.py owns."""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))

from hardware.maxarm import petri  # noqa: E402
from hardware.maxarm import kinematics as kin  # noqa: E402

ROOM_ID = HERE.name


def world_of(xy_arm_mm, z_mm: float = 0.0):
    """Arm-frame (mm) -> world (m): mirror x, then the base's pose (facing -y)."""
    bx, by, bz = petri.ROOM_BASE_POS_M
    x, y = xy_arm_mm
    return [round(bx - x / 1000.0, 4), round(by + y / 1000.0, 4), round(bz + z_mm / 1000.0, 4)]


def room() -> dict:
    objects = []
    names = ("dish1", "dish2", "dish3")
    for name, c in zip(names, petri.dish_centres_arm()):
        objects.append({"name": f"{name}_base", "source": "mjcf:petri_base.xml",
                        "pose": {"pos": world_of(c)}, "dynamic": True, "type": "other",
                        "label": f"{name} base", "grippable": True,
                        "aliases": [f"{name} dish", f"{name} bottom"]})
        objects.append({"name": f"{name}_lid", "source": "mjcf:petri_lid.xml",
                        "pose": {"pos": world_of(c, petri.SEATED_LID_BOTTOM_MM)}, "dynamic": True,
                        "type": "other", "label": f"{name} lid", "grippable": True,
                        "aliases": [f"{name} cover"]})
    for c in petri.dish_centres_arm():
        for z in (kin.TABLE_CONTACT_Z_MM + petri.SEATED_LID_TOP_MM, 150.0):
            bad = kin.check_pose((c[0], c[1], z), kin.TABLE_CONTACT_Z_MM + 3.0)
            assert not bad, f"dish at {c} unreachable at z {z}: {bad}"
    for c in petri.aside_spots_arm():
        for z in (kin.TABLE_CONTACT_Z_MM + petri.LID_ALONE_TOP_MM, 150.0):
            bad = kin.check_pose((c[0], c[1], z), kin.TABLE_CONTACT_Z_MM + 3.0)
            assert not bad, f"aside spot at {c} unreachable at z {z}: {bad}"
    bx, by, bz = petri.ROOM_BASE_POS_M
    aside = ", ".join(f"({x:.0f}, {y:.0f})" for x, y in petri.aside_spots_arm())
    return {
        "id": ROOM_ID,
        "name": "MaxArm and Petri dishes",
        "description": (
            "The lab bench with the xArm6 on its rail (idle, the room's controllable robot) and the "
            "Hiwonder MaxArm (suction cup, wrist D435) standing on the bench in front of the rail at "
            f"({bx}, {by}) facing the bench's front edge. Three 90 mm Petri dishes, lid on, stand on "
            f"an arc {petri.DISH_RADIUS_MM:.0f} mm from the MaxArm's base, with a clear set-aside spot "
            "for each lid. Built for rehearsing scripts/maxarm_lid_twin.py: lift each lid, set it "
            "aside, put it back. Generated by make_room.py from hardware/maxarm/petri.py."),
        "environment": {"extract_from": "../../envs/lab_scene.xml",
                        "bodies": ["bench", "observers"], "floor": True, "lights": True},
        "robots": [
            {"instance": "arm0", "type": "xarm6_rail",
             "base_pose": {"pos": [0, 0, 0], "euler": [0, 0, 0]},
             "end_effector": "parallel_gripper", "controllable": True},
            {"instance": "arm1", "type": "maxarm",
             "base_pose": {"pos": [bx, by, bz], "euler": [0, 0, 0]},
             "end_effector": "suction", "controllable": False},
        ],
        "objects": objects,
        "cameras": [
            {"name": "cam_overhead", "role": "vision"},
            {"name": "cam_tripod", "role": "observer"},
            {"name": "cam_maxarm", "role": "observer", "fovy": 36.0,
             "pos": [round(bx + 0.50, 3), round(by - 0.78, 3), 1.14],
             "lookat": [round(bx - 0.03, 3), round(by - 0.16, 3), 0.79]},
        ],
        "workspace_bounds": {"min": [None, None, None], "max": [None, None, None]},
        "agent": {
            "context": (
                "A second robot, the Hiwonder MaxArm, stands on the bench at "
                f"({bx}, {by}) and is driven by its own script, not by you. Three Petri dishes "
                "(88 mm bases, 92 mm lids) stand in front of it near the bench's front edge; leave "
                "them to it. Set-aside spots for the lids, in the MaxArm's own frame (mm): " + aside + "."),
            "task_ideas": ["go home", "move the gripper 150 mm above the bench centre"],
        },
    }


def main() -> int:
    (HERE / "petri_base.xml").write_text(petri.base_mjcf())
    (HERE / "petri_lid.xml").write_text(petri.lid_mjcf())
    (HERE / "room.json").write_text(json.dumps(room(), indent=2) + "\n")
    print(f"wrote {HERE.relative_to(ROOT)}/room.json, petri_base.xml, petri_lid.xml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
