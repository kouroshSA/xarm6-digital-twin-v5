"""Generate rooms/lab_a2s2_rebuilt/room.json: the lab, expressed in the room
format instead of loaded from envs/lab_scene.xml.

    python scripts/make_lab_rebuilt.py          # writes the room.json
    python scripts/make_lab_rebuilt.py --check  # exit 1 if it would change

Cubes, bins, racks and tubes become builtin objects with the lab object's
size, colour, mass and pose; the cup, plates, tip box, OT-2 and instruments
are copied out of the lab scene at build time (mjcf:<scene>#<body>), keeping
their names. Types, labels, aliases and drivers come from rooms/lab_a2s2.
The robot (with the rail LED strips) is the xarm6_rail type, the bench and
room from the lab scene. twin_rooms.test_lab_rebuilt checks the result
against the lab: counts, every body within 1 mm, and a scripted pick.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import mujoco
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)

from twin_rooms import load_room  # noqa: E402

LAB_XML = "envs/lab_scene.xml"
OUT = ROOT / "rooms" / "lab_a2s2_rebuilt" / "room.json"
REL_SCENE = "../../envs/lab_scene.xml"


def _rgba(m, g):
    mid = int(m.geom_matid[g])
    return [round(float(v), 4) for v in (m.mat_rgba[mid] if mid >= 0 else m.geom_rgba[g])]


def _pose(m, b):
    pos = [round(float(v), 5) for v in m.body_pos[b]]
    euler = np.zeros(3)
    q = m.body_quat[b]
    # MuJoCo's default eulerseq "xyz" (intrinsic): R = Rx(a) Ry(b) Rz(c)
    R = np.zeros(9)
    mujoco.mju_quat2Mat(R, q)
    R = R.reshape(3, 3)
    b_ = np.arcsin(np.clip(R[0, 2], -1, 1))
    a = np.arctan2(-R[1, 2], R[2, 2])
    c = np.arctan2(-R[0, 1], R[0, 0])
    euler = [round(float(np.degrees(v)), 4) + 0.0 for v in (a, b_, c)]
    return {"pos": pos, "euler": euler} if any(abs(e) > 1e-6 for e in euler) else {"pos": pos}


def build() -> dict:
    lab = load_room("lab_a2s2")
    m = mujoco.MjModel.from_xml_path(LAB_XML)
    geoms = lambda b: [g for g in range(m.ngeom) if m.geom_bodyid[g] == b]  # noqa: E731
    objects = []
    for o in lab.objects:
        if o.type == "fixture":             # the rail LED strips belong to the robot
            continue
        b = m.body(o.name).id
        d = {"name": o.name}
        if o.type == "cube":
            g = geoms(b)[0]
            d.update(source="builtin:cube", params={
                "size": [round(2 * float(v), 4) for v in m.geom_size[g]],
                "rgba": _rgba(m, g), "mass": round(float(m.body_mass[b]), 4)},
                pose=_pose(m, b))
        elif o.type == "bin" and o.name.endswith("_bin"):
            floor = m.geom(f"{o.name}_floor").id
            d.update(source="builtin:bin", params={"rgba": _rgba(m, floor)}, pose=_pose(m, b))
        elif o.type == "rack":
            d.update(source="builtin:tube_rack", pose=_pose(m, b))
        elif o.type == "tube":
            d.update(source="builtin:tube",
                     params={"cap_rgba": _rgba(m, m.geom(f"{o.name}_cap").id)},
                     pose=_pose(m, b))
        else:
            d.update(source=f"mjcf:{REL_SCENE}#{o.name}")
        raw = next(r for r in lab.raw["objects"] if r["name"] == o.name)
        for k in ("dynamic", "type", "label", "aliases", "grippable", "driver"):
            if k in raw:
                d[k] = raw[k]
        objects.append(d)
    return {
        "id": "lab_a2s2_rebuilt",
        "name": "A2S2 wet lab bench (rebuilt)",
        "description": "The lab, rebuilt in the room format: bench and room from the lab "
                       "scene, the xarm6_rail robot, cubes/bins/racks/tubes as builtin objects "
                       "and the cup, plates, tip box, OT-2 and instruments copied out of the "
                       "lab scene. Generated by scripts/make_lab_rebuilt.py; checked against "
                       "lab_a2s2 by twin_rooms.test_lab_rebuilt. lab_a2s2 stays the default.",
        "environment": {"extract_from": REL_SCENE,
                        "bodies": ["lab_environment", "bench", "observers"],
                        "floor": True, "lights": True},
        "robots": [{"instance": "arm0", "type": "xarm6_rail",
                    "base_pose": {"pos": [0, 0, 0], "euler": [0, 0, 0]},
                    "end_effector": "parallel_gripper", "controllable": True}],
        "objects": objects,
        "cameras": lab.raw.get("cameras", []),
        "agent": {"context": "", "prompt_file": "../lab_a2s2/agent_prompt.md",
                  "task_ideas": lab.task_ideas},
    }


if __name__ == "__main__":
    text = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv:
        same = OUT.is_file() and OUT.read_text() == text
        print("up to date" if same else f"{OUT} would change; rerun without --check")
        sys.exit(0 if same else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(build()['objects'])} objects)")
