# simready_import/manifest.py
"""assets/simready/manifest.json: one entry per imported asset slug, recording
where it came from (repo, path, the pinned revision sha), its licence, the
source's units and up axis, the conversion options, and a sha256 of every file
written -- so an imported asset can be traced back and checked for edits."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Optional

from simready_import import ASSETS_DIR, MANIFEST


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def load(path: Path = MANIFEST) -> Dict[str, dict]:
    return json.loads(path.read_text()) if path.is_file() else {}


def save(entries: Dict[str, dict], path: Path = MANIFEST) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(dict(sorted(entries.items())), indent=2) + "\n")


def record(slug: str, *, repo_id: str, path_in_repo: str, revision: str, license: str,
           source_units_m: float, source_up_axis: str, variant: str, options: dict,
           asset_dir: Path, bbox_mm, mass_kg: float, labels: dict,
           links: Optional[dict] = None, manifest_path: Path = MANIFEST) -> dict:
    files = {p.name: sha256(p) for p in sorted(asset_dir.iterdir()) if p.is_file()}
    entry = {
        "repo_id": repo_id, "path_in_repo": path_in_repo, "revision": revision,
        "license": license, "source_meters_per_unit": source_units_m,
        "source_up_axis": source_up_axis, "physics_variant": variant,
        "options": options, "bbox_mm": [round(float(v), 1) for v in bbox_mm],
        "mass_kg": round(float(mass_kg), 5), "labels": labels,
        **({"links": links} if links else {}), "files": files,
        "imported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    entries = load(manifest_path)
    entries[slug] = entry
    save(entries, manifest_path)
    write_attribution(entries, manifest_path.parent / "ATTRIBUTION.md")
    return entry


#: Who to credit per source dataset (CC-BY-4.0 requires naming the creator).
DATASET_CREDIT = {
    "nvidia/simready-assets": "NVIDIA Corporation",
    "ForgeCAD/simready-assets": "ForgeCAD",
    "PalatialSim/palatial-nv-asset-library": "Palatial",
}


def write_attribution(entries: Dict[str, dict], path: Path) -> None:
    """ATTRIBUTION.md, GENERATED from the manifest so it cannot fall behind it
    (the hand-written one listed 3 of 12 imported assets)."""
    lines = ["# Attribution", "",
             "GENERATED by `simready_import` from `manifest.json` -- do not edit.", "",
             "The assets in this folder are converted from SimReady (OpenUSD) assets "
             "published as Hugging Face datasets. Each is used under the licence shown, "
             "and `manifest.json` records the exact source file, the pinned revision and a "
             "sha256 of every converted file.", ""]
    for repo in sorted({e["repo_id"] for e in entries.values()}):
        rows = sorted((k, e) for k, e in entries.items() if e["repo_id"] == repo)
        lics = sorted({e["license"] for _, e in rows})
        lines += [f"## [{repo}](https://huggingface.co/datasets/{repo})", "",
                  f"Copyright {DATASET_CREDIT.get(repo, repo.split('/')[0])}. "
                  f"Licence: {', '.join(lics)}"
                  + (" ([CC-BY-4.0](https://creativecommons.org/licenses/by/4.0/))"
                     if lics == ["CC-BY-4.0"] else "") + ".", "",
                  "| slug | source asset | revision |", "|---|---|---|"]
        lines += [f"| `{k}` | `{e['path_in_repo']}` | `{e['revision'][:12]}` |" for k, e in rows]
        lines.append("")
    lines += ["**Changes made** by `simready_import`:",
              "- converted from OpenUSD to MuJoCo MJCF with OBJ meshes;",
              "- fixed-jointed parts merged into one rigid body (or, for articulated assets, "
              "into their links, with revolute/prismatic joints kept);",
              "- the origin moved to the bounding-box centre;",
              "- convex collision hulls computed (CoACD pieces for concave parts, plus thin "
              "support plates under floors and shelves of articulated assets);",
              "- meshes decimated above a triangle budget, textures downscaled to at most 1024 px;",
              "- rolling and torsional friction added; joint damping, friction loss and "
              "return springs set;",
              "- grip handles added on moving parts; prims listed under `options.exclude` "
              "in the manifest left out.", ""]
    path.write_text("\n".join(lines))


def entry(slug: str, manifest_path: Path = MANIFEST) -> Optional[dict]:
    return load(manifest_path).get(slug)


def asset_dir(slug: str) -> Path:
    return ASSETS_DIR / slug
